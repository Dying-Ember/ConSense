const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const template = fs.readFileSync(path.join(__dirname, 'progress-report-template.html'), 'utf8');
const script = template.match(/<script>\s*([\s\S]*?)<\/script>/)[1];
new vm.Script(script);
const source = script.slice(script.indexOf('function buildQualityTrendSeries('), script.indexOf('const qualityTrendSeries='));
const build = new Function(`${source}; return buildQualityTrendSeries;`)();
const trainingSource = script.slice(script.indexOf('function buildTrainingRuns('), script.indexOf('function renderTrainingHistory('));
const buildTraining = new Function(`${trainingSource}; return buildTrainingRuns;`)();
const ledger = JSON.parse(fs.readFileSync(process.argv[2] || path.join(__dirname, '../../docs/testing/oer-progress-ledger.json'), 'utf8'));
const before = JSON.stringify(ledger.documentScorecards);
const actual = build(ledger.documentScorecards);
assert.equal(JSON.stringify(ledger.documentScorecards), before);
assert.equal(actual.length, 3);
assert.deepEqual(actual[0].points.slice(0, 2).map(p => [p.round, p.numerator]), [[127, 62], [128, 66]]);
assert.deepEqual(actual[1].points.slice(0, 2).map(p => [p.round, p.numerator]), [[125, 14], [131, 15]]);
assert.deepEqual(actual[2].points.slice(0, 1).map(p => [p.round, p.numerator]), [[129, 3]]);
assert.deepEqual(actual.map(s => s.denominator), [66, 55, 3]);

const metricId = actual[0].id;
const cards = points => [{id: 'test-card', metrics: [{id: metricId, denominator: 4, unit: 'items', evidence: ['test-evidence'], points}]}];
const point = (label, numerator) => ({label, numerator});
assert.deepEqual(build(cards([point('R9 source check', 4), point('R2 baseline', 0)]))[0].points.map(p => [p.round, p.ratio]), [[2, 0], [9, 1]]);
assert.equal(build(cards([point('R3 pending', null), point('No scored round', 2)]))[0].points.length, 0);
assert.equal(build([])[0].points.length, 0);
assert.throws(() => build(cards([point('R2 out of range', 5)])), /numerator/);
assert.throws(() => build(cards([point('R2 fractional', 1.5)])), /numerator/);
assert.throws(() => build(cards([point('R2 first', 1), point('R2 conflicting', 2)])), /Duplicate/);
const badDenominator = cards([point('R2 source', 1)]);
badDenominator[0].metrics[0].denominator = 0;
assert.throws(() => build(badDenominator), /denominator/);
assert.ok(template.indexOf('id="quality-trend"') < template.indexOf('<section class="hero">'));
assert.ok(template.indexOf('id="training-history"') < template.indexOf('id="quality-trend"'));
const sampleRun = {id: 'run-1', updates: 2, forwards: 4, losses: [{step: 0, micro: 0, loss: 4}, {step: 0, micro: 1, loss: 2}, {step: 1, micro: 0, loss: 1}, {step: 1, micro: 1, loss: 2}]};
const history = runs => ({runs});
const sampleBefore = JSON.stringify(sampleRun);
const calculated = buildTraining(history([sampleRun]))[0];
assert.equal(JSON.stringify(sampleRun), sampleBefore);
assert.deepEqual(calculated.steps.map(p => [p.step, p.mean, p.position]), [[0, 3, .5], [1, 1.5, 2.5]]);
assert.equal(calculated.reduction, .5);
assert.deepEqual(buildTraining(), []);
assert.throws(() => buildTraining(history([sampleRun, sampleRun])), /ID/);
const alter = change => ({...sampleRun, ...change});
assert.throws(() => buildTraining(history([alter({forwards: 5})])), /counts/);
assert.throws(() => buildTraining(history([alter({losses: sampleRun.losses.map(p => ({...p, loss: NaN}))})])), /observation/);
assert.throws(() => buildTraining(history([alter({losses: [sampleRun.losses[0], sampleRun.losses[0], ...sampleRun.losses.slice(2)]})])), /Duplicate/);
assert.throws(() => buildTraining(history([alter({losses: sampleRun.losses.map(p => ({...p, step: p.step * 2}))})])), /step/);
assert.throws(() => buildTraining(history([alter({updates: 3})])), /Incomplete/);
assert.equal(buildTraining(history([alter({losses: sampleRun.losses.map(p => ({...p, loss: 0}))})]))[0].reduction, null);
assert.equal(buildTraining(history([alter({losses: sampleRun.losses.map(p => ({...p, loss: p.step ? 4 : 2}))})]))[0].reduction, -1);
const actualRuns = buildTraining(ledger.trainingHistory);
if (ledger.trainingHistory) {
  assert.ok(actualRuns.length >= 5);
  assert.equal(actualRuns.slice(0, 5).reduce((n, r) => n + r.forwards, 0), 216);
  assert.equal(actualRuns.slice(0, 5).reduce((n, r) => n + r.updates, 0), 84);
}
assert.ok(script.includes('s.points.length>1?'));
