const assert = require('node:assert/strict')
const path = require('node:path')
const vue = require('vue')
const { loadVue } = require('./helpers/load-vue.cjs')
const { renderer, find, text, settle } = require('./helpers/render-controls.cjs')
const calls = [], questionLinks = []
const candidate = { value: '42', sourceQuote: 'Duration is 42 months.', fileName: 'Minutes.docx', sourceDocumentId: 1 }
const current = { key: 'current', label: { en: 'Current duration' }, kind: 'number', candidates: [] }
const response = { runId: 'saved-run', variables: [current, { key: 'changed-list', label: { en: 'Changed bill list' }, kind: 'list', candidates: [] },
  { key: 'enabled', label: { en: 'Enabled' }, kind: 'boolean', candidates: [{ ...candidate, value: 'true' }] },
  { key: 'details', label: { en: 'Details' }, kind: 'record', candidates: [{ ...candidate, value: '{"discovery-field-address":"Site office","id":"internal-identity"}' }] }
], catalog: { groups: [{ fields: [{ key: 'details', label: { en: 'Details' }, kind: 'object', columnFields: [{ key: 'discovery-field-address', label: { en: 'Office address' }, kind: 'text' }] }] }] }, unassignedVariables: [{ key: 'retired', label: { en: 'Previous duration' }, kind: 'number', candidates: [candidate] }] }
response.catalog.groups[0].fields.push({ key: 'changed-list', label: { en: 'Changed bill list' }, kind: 'list', columnFields: [{ key: 'new-column', label: { en: 'New unrelated column' }, kind: 'text' }] })
response.candidateDefinitions = { 'original-list-definition': { key: 'changed-list', label: { en: 'Original bill list' }, kind: 'list', columnFields: [{ key: 'old-column', label: { en: 'Original bill description' }, kind: 'text' }] } }
response.unassignedVariables.push({ key: 'changed-list', label: { en: 'Changed bill list' }, kind: 'list', candidates: [{ ...candidate, fieldDefinitionHash: 'original-list-definition', value: '[{"old-column":"Site safety","_itemId":"row-1"}]' }] })
response.catalog.groups[0].fields.at(-1).columnFields.push({ key: 'new-number', label: { en: 'Current bill number' }, kind: 'text' })
response.candidateDefinitions['original-list-definition'].columnFields.push({ key: 'old-number', label: { en: 'Original bill number' }, kind: 'text' })
response.unassignedVariables.at(-1).candidates[0].value = '[{"old-column":"Site safety","old-number":"7","_itemId":"row-1"}]'
const loaded = loadVue(path.join(__dirname, '../src/components/DraftingCandidateReview.vue'), { boundaries: { '@/api': { draftingApi: {
  reviewCandidates: async () => response,
  reviewCorrectCandidate: async (...args) => { calls.push(args); if (args[2] === 'changed-list') return response; return { runId: 'corrected-run', variables: [{ ...current, candidates: [candidate] }], unassignedVariables: [] } }
} } } })
const host = renderer(), app = host.createApp({ setup: () => () => vue.h(loaded.default, { projectId: 'P', revisionId: 'R', locale: 'en', reloadKey: 0, onQuestion: (...args) => questionLinks.push(args) }) })
app.mount(host.root)
;(async () => {
  await settle()
  const candidateSearch = find(host.root, node => node.props?.['data-candidate-search'] !== undefined)
  const searchFor = async value => { candidateSearch.props['onUpdate:modelValue'](value); await settle() }
  const count = () => text(find(host.root, node => node.props?.['data-candidate-count'] !== undefined))
  assert.match(count(), /4 \/ 4/)
  await searchFor('  DETAILS  '); assert.match(count(), /1 \/ 4/)
  assert.match(text(host.root), /Site office/); assert.doesNotMatch(text(host.root), /Previous duration/)
  await searchFor('Minutes.docx'); assert.match(count(), /4 \/ 4/)
  await searchFor('Duration is 42'); assert.match(count(), /4 \/ 4/)
  await searchFor('missing source text'); assert.match(count(), /0 \/ 4/); assert.match(text(host.root), /No matching candidates/)
  await searchFor(''); assert.match(count(), /4 \/ 4/); assert.equal(calls.length, 0)
  await find(host.root, node => node.props?.['data-candidate-question'] !== undefined).props.onClick()
  assert.deepEqual(questionLinks, [['enabled', 'R']])
  assert.equal(calls.length, 0, 'Question navigation does not correct or adopt a value')
  assert.ok(!find(find(host.root, node => node.tag === 'article' && /Previous duration/.test(text(node))), node => node.props?.['data-candidate-question'] !== undefined), 'Retired candidate cannot navigate to an unrelated current question')
  assert.match(text(host.root), /original question was merged or retired/)
  assert.match(text(host.root), /Duration is 42 months/)
  assert.match(text(host.root), /Yes/)
  assert.match(text(host.root), /Site office/)
  assert.match(text(host.root), /Office address/)
  assert.doesNotMatch(text(host.root), /internal-identity|discovery.field.address/)
  assert.match(text(host.root), /Original bill description/)
  assert.match(text(host.root), /Site safety/)
  assert.doesNotMatch(text(host.root), /New unrelated column/)
  const changedList = find(host.root, node => node.tag === 'article' && /Changed bill list/.test(text(node)))
  await find(changedList, node => node.tag === 'button' && text(node) === 'Correct candidate or assignment').props.onClick(); await settle()
  assert.equal(find(host.root, node => node.props?.['data-candidate-target'] !== undefined).value, '', 'Changed active definitions require explicit reassignment too')
  assert.match(text(find(host.root, node => node.tag === 'form')), /Original bill description/)
  const listTarget = find(host.root, node => node.props?.['data-candidate-target'] !== undefined)
  listTarget.props['onUpdate:modelValue']('changed-list'); await settle()
  assert.equal(candidateSearch.props.disabled, true, 'An unsaved correction cannot be hidden by filtering')
  const listForm = find(host.root, node => node.tag === 'form')
  await listForm.props.onSubmit({ preventDefault() {} }); await settle(); assert.equal(calls.length, 0, 'Missing column assignments cannot save')
  const column = find(host.root, node => node.props?.['data-candidate-column'] === 'old-column')
  assert.ok(column); column.props['onUpdate:modelValue']('new-column'); await settle()
  const numberColumn = find(host.root, node => node.props?.['data-candidate-column'] === 'old-number')
  numberColumn.props['onUpdate:modelValue']('new-column'); await settle()
  await listForm.props.onSubmit({ preventDefault() {} }); await settle(); assert.equal(calls.length, 0, 'Two source columns cannot overwrite the same destination')
  numberColumn.props['onUpdate:modelValue']('new-number'); await settle()
  assert.match(text(find(host.root, node => node.props?.['data-candidate-column-mapping'] !== undefined)), /Site safety/)
  await listForm.props.onSubmit({ preventDefault() {} }); await settle()
  assert.equal(calls.length, 1)
  assert.deepEqual(JSON.parse(calls[0][3].value), [{ 'new-column': 'Site safety', 'new-number': '7', _itemId: 'row-1' }], 'Explicit mapping retains row identity and every value')
  calls.length = 0
  await find(changedList, node => node.tag === 'button' && text(node) === 'Correct candidate or assignment').props.onClick(); await settle()

  await find(host.root, node => node.tag === 'button' && text(node) === 'Cancel correction').props.onClick(); await settle()
  const details = find(host.root, node => node.tag === 'article' && /Details/.test(text(node)))
  await find(details, node => node.tag === 'button' && text(node) === 'Correct candidate or assignment').props.onClick(); await settle()
  const address = find(host.root, node => node.props?.id === 'candidate-details-discovery-field-address')
  assert.ok(address, 'Use the existing named field editor rather than asking for JSON')
  assert.equal(address.props.value, 'Site office')
  await find(host.root, node => node.tag === 'button' && text(node) === 'Cancel correction').props.onClick(); await settle()
  const retired = find(host.root, node => node.tag === 'article' && /Previous duration/.test(text(node)))
  const edit = find(retired, node => node.tag === 'button' && text(node) === 'Correct candidate or assignment')
  await edit.props.onClick(); await settle()
  const target = find(host.root, node => node.props?.['data-candidate-target'] !== undefined)
  assert.equal(target.value, '')
  const search = find(host.root, node => node.props?.['data-candidate-target-search'] !== undefined)
  search.props['onUpdate:modelValue']('  DURATION  '); await settle()
  assert.match(text(target), /Current duration/)
  assert.doesNotMatch(text(target), /Enabled|Changed bill list/)
  assert.equal(target.value, '', 'Searching must not choose a destination')
  search.props['onUpdate:modelValue']('no such question'); await settle()
  assert.match(text(host.root), /No matching questions/)
  search.props['onUpdate:modelValue']('duration'); await settle()
  const form = find(host.root, node => node.tag === 'form')
  await form.props.onSubmit({ preventDefault() {} }); await settle(); assert.equal(calls.length, 0)
  target.props['onUpdate:modelValue']('current'); await settle()
  search.props['onUpdate:modelValue']('Enabled'); await settle()
  assert.match(text(target), /Current duration/, 'Keep the explicitly selected question visible even outside search results; the saved target is checked below')
  await form.props.onSubmit({ preventDefault() {} }); await settle()
  assert.equal(calls.length, 1); assert.equal(calls[0][2], 'retired'); assert.equal(calls[0][3].targetKey, 'current'); assert.equal(calls[0][3].candidateIndex, 0)
  assert.doesNotMatch(text(host.root), /original question was merged or retired/)
  assert.match(text(host.root), /Current duration/)
  app.unmount()
  console.log('PASS: retired candidates retain evidence, require explicit reassignment and reuse correction without adoption')
})().catch(error => { console.error(error); process.exitCode = 1 })
