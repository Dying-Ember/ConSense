const assert = require('node:assert/strict')
const path = require('node:path')
const { loadTypeScript } = require('./helpers/load-typescript.cjs')
const api = loadTypeScript(path.join(__dirname, '../src/drafting/human-review-project-candidates.ts'), { globals: { structuredClone } })
const plain = value => JSON.parse(JSON.stringify(value))
const empty = { combined: '', foundations: '', months: '' }
let state = api.newCandidateReview()
const initialState = state, initial = plain(state)
assert.equal(state.compoundSplit, false)
assert.deepEqual(plain(api.acceptedProjectAnswers(state)), empty, 'Recognized candidates are not project facts.')
assert.throws(() => api.adoptCandidate(state, 'combined'), /Split/)
assert.throws(() => api.adoptManual(state, 'foundations', 'yes', 'Manual decision'), /Split/)
assert.throws(() => api.adoptCandidate(state, 'months'), /Demonstration/)
state = api.correctCandidate(state, 'months', ' 042.0 ', '合约工期42个月。')
assert.equal(state.candidates.months.value, '42')
assert.deepEqual(plain(api.acceptedProjectAnswers(state)), empty, 'Correction never adopts a candidate.')
state = api.splitCombinedCandidate(state)
assert.deepEqual(plain(api.acceptedProjectAnswers(state)), empty, 'Splitting uses two explicit source sentences and adopts neither.')
assert.notEqual(state.candidates.combined.quote, state.candidates.foundations.quote)
for (const candidate of Object.values(state.candidates)) {
  assert.equal(api.PROJECT_SAMPLE_SOURCE_TEXT.slice(candidate.sourceStart, candidate.sourceEnd), candidate.quote)
}
const retargeted = api.retargetCandidate(state, 'combined', 'foundations')
assert.equal(retargeted.candidates.foundations.quote, state.candidates.combined.quote)
assert.ok(retargeted.candidates.foundations.issue)
assert.throws(() => api.adoptCandidate(retargeted, 'foundations'), /Demonstration/)
assert.deepEqual(plain(api.acceptedProjectAnswers(retargeted)), empty)
assert.throws(() => api.correctCandidate(state, 'months', '42', '另一个文件的文字'), /Quote/)
for (const invalid of ['-1', 'Infinity', 'NaN', 'not a number']) assert.throws(() => api.correctCandidate(state, 'months', invalid, '合约工期42个月。'))
state = api.correctCandidate(state, 'months', '', '合约工期42个月。')
assert.throws(() => api.adoptCandidate(state, 'months'), /Unknown/)
assert.throws(() => api.adoptManual(state, 'months', '42', ' '), /reason/)
state = api.adoptManual(state, 'months', '50', 'Fictional user decision for this demonstration')
state = api.adoptCandidate(api.adoptCandidate(state, 'combined'), 'foundations')
const beforeRerun = plain(state.adopted)
state = api.rerunCandidates(state)
assert.equal(state.adopted.months.value, '50', 'Identifying again never overwrites an adopted manual value.')
assert.equal(state.adopted.months.origin, 'manual')
assert.equal(state.adopted.months.reason, beforeRerun.months.reason)
assert.equal(state.adopted.months.reviewRequired, true, 'Changed suggestions require review of the retained adoption.')
assert.equal(api.acceptedProjectAnswers(state).months, '')
assert.equal(api.acceptedProjectAnswers(state).combined, 'yes', 'Unchanged suggestions keep unrelated adoptions usable.')
state = api.adoptManual(state, 'months', '50', 'Retained after reviewing the new candidate')
state = api.rerunCandidates(state)
assert.equal(api.acceptedProjectAnswers(state).months, '50', 'An unchanged rerun preserves an explicitly reviewed manual answer.')
const adopted = plain(state.adopted)
state = api.markSourceChanged(state)
assert.deepEqual(Object.values(state.adopted).map(item => item.value), Object.values(adopted).map(item => item.value))
assert.deepEqual(plain(api.acceptedProjectAnswers(state)), empty, 'Source changes retain historical values but exclude them from a new plan.')
assert.throws(() => api.adoptCandidate(state, 'months'), /Source changed/)
state = api.rerunCandidates(state)
assert.deepEqual(plain(api.acceptedProjectAnswers(state)), empty, 'A rerun cannot silently clear source-change review requirements.')
state = api.adoptCandidate(state, 'months')
assert.equal(api.acceptedProjectAnswers(state).months, '42')
state = api.withdrawAdoption(state, 'months')
assert.equal(api.acceptedProjectAnswers(state).months, '')
assert.deepEqual(plain(initialState), initial, 'Pure updates leave prior states intact.')
assert.equal(api.PROJECT_SAMPLE_SOURCE_TEXT, '本次招标采用联合合约。工程范围包括基础工程。合约工期42个月。')
console.log('PASS fictional project candidates: exact quotes, compound split, correction, assignment, explicit adoption, manual retention and source-change review; no extraction or graph mutation.')
