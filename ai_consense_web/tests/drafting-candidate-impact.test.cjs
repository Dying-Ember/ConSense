const assert = require('node:assert/strict')
const path = require('node:path')
const vue = require('vue')
const { loadVue } = require('./helpers/load-vue.cjs')
const { renderer, text, settle } = require('./helpers/render-controls.cjs')
const node = (id, targets = []) => ({ id, nameEn: id, status: 'pending', type: { kind: 'text' }, role: { kind: 'input' }, docIds: ['66'], editTargets: targets, sourceAnchors: [], relations: [] })
const review = { id: 'R', sourceStale: false, graph: { graph: { variables: [node('answer'), node('other'), node('owner', [{ docId: '66', text: 'Section ____*', action: 'fill', valueSourceId: 'answer', needsRebind: true }, { docId: '66', text: '____\n___', action: 'check', valueSourceId: 'answer', nativeBinding: { status: 'bound' } }]), { ...node('retired', [{ docId: '66', text: 'RETIRED TARGET', valueSourceId: 'answer' }]), status: 'excluded' }] }, sources: [{ id: '66', fileKey: 'SCC', format: 'docx', fileName: 'Original SCC.docx' }] } }
const before = JSON.stringify(review)
let reads = 0, writes = 0
const loaded = loadVue(path.join(__dirname, '../src/components/DraftingCandidateReview.vue'), { boundaries: { '@/api': { draftingApi: {
 reviewCandidates: async () => { reads++; return { runId: 'saved', variables: ['answer', 'other'].map(key => ({ key, label: { en: key }, kind: 'text', candidates: [{ value: 'Section 3', sourceQuote: 'Exact source', fileName: 'minutes.docx' }] })), catalog: { groups: [] } } },
 reviewCorrectCandidate: async () => { writes++; throw Error('Unexpected write') }
} } } })
const props = vue.reactive({ projectId: 'P', revisionId: 'R', locale: 'en', reloadKey: 0, review })
const host = renderer(), app = host.createApp({ setup: () => () => vue.h(loaded.default, props) })
app.mount(host.root)
;(async () => {
 await settle()
 assert.match(text(host.root), /Linked amendment impact \(not executed\)/)
 assert.match(text(host.root), /Original SCC.docx/)
 assert.match(text(host.root), /Placeholder targets：1/)
 assert.equal((text(host.root).match(/Original SCC.docx/g) || []).length, 1, 'One filename per source group')
 assert.match(text(host.root), /Source ranges bound：1.*Amendments awaiting review：2/)
 assert.match(text(host.root), /Amendments awaiting review will not execute/)
 assert.match(text(host.root), /without an applicability condition/)
 assert.doesNotMatch(text(host.root), /____\n___/)
 assert.match(text(host.root), /Section ____\*/)
 assert.match(text(host.root), /No direct amendment action is linked/)
 assert.doesNotMatch(text(host.root), /RETIRED TARGET/)
 const pendingRule = JSON.parse(JSON.stringify(review))
 const owner = pendingRule.graph.graph.variables.find(item => item.id === 'owner')
 owner.correction = { kind: 'rule', needsRebind: true, branches: [{ id: 'case', mode: 'all', clauses: [] }] }
 owner.editTargets.forEach(target => { target.action = 'fill'; target.needsRebind = false; target.nativeBinding = { status: 'bound' }; target.branchId = 'case' })
 props.review = pendingRule; await settle()
 assert.match(text(host.root), /Source ranges bound：2.*Amendments awaiting review：2/, 'Unresolved rule keeps bound target amendments pending')
 owner.correction.needsRebind = false
 props.review = JSON.parse(JSON.stringify(pendingRule)); await settle()
 assert.match(text(host.root), /Source ranges bound：2.*Amendments awaiting review：0/, 'Resolved rule does not invent a remaining review blocker')
 props.review = { ...review, id: 'OLDER' }; await settle()
 assert.match(text(host.root), /variable revision or source changed/)
 assert.doesNotMatch(text(host.root), /Section ____\*/)
 props.review = { ...review, sourceStale: true }; await settle()
 assert.doesNotMatch(text(host.root), /Section ____\*/)
 assert.equal(reads, 1, 'Impact inspection reuses the supplied graph without extra API reads')
 assert.equal(writes, 0)
 assert.equal(JSON.stringify(review), before, 'Graph projection preserves stored target and candidate authority')
 app.unmount()
 console.log('PASS: candidate impact reuses graph relationships, excludes retired actions, rejects stale revisions and performs no writes')
})().catch(error => { console.error(error); process.exitCode = 1 })
