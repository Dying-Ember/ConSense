export type DraftWord = keyof typeof triples
export function draftWord(key: DraftWord, locale: AppLocale): string { return triples[key][locale === 'en' ? 2 : locale === 'zh-Hant' ? 1 : 0] }
export function localized(text: LocalizedText | string | undefined | null, locale: AppLocale): string {
  if (!text) return ''
  if (typeof text === 'string') return text
  return text[locale === 'en' ? 'en' : locale === 'zh-Hant' ? 'zhHant' : 'zhHans'] || text.en || text.zhHans || ''
}
